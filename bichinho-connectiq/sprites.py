for k, v in S.items():
    rows = v.strip().split('\n'); assert all(len(r) == len(rows[0]) for r in rows), k
    n = num(rows)
    mc.append(f'    const {k} = [{", ".join(map(str, n))}];')
    js.append(f'  {k}: [{", ".join(map(str, n))}],')
mc.append('}'); js.append('};')
